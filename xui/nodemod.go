package ui

import (
	"fmt"

	"ily.dev/domi"
	"ily.dev/domi/attr"
)

// A Modifier configures the behavior of a View.
// It can be applied with [View.Modify].
//
// It is usually more convenient to call modifier methods directly on View.
type Modifier interface {
	applyTo(box) box
}

// contextual is implemented by modifiers and wrappers that adjust the
// render context their subtree sees, on top of their effect on the box
// itself: the box acts bottom-up, the context flows top-down.
type contextual interface {
	context(renderContext) renderContext
}

// nodeMod applies a modifier to its node's box.
type nodeMod struct {
	mod  Modifier
	node node
}

func (m nodeMod) render(rc renderContext) box {
	if c, ok := m.mod.(contextual); ok {
		rc = c.context(rc)
	}
	x := m.node.render(rc)
	if x.raw != nil {
		panic(fmt.Sprintf("ui: %T applied to a Domi view, which has no ui-managed element", m.mod))
	}
	return m.mod.applyTo(x)
}

// Modify applies the given modifiers to v in order from left to right.
func (v base) Modify(mods ...Modifier) View {
	for _, m := range mods {
		out := make(base, len(v))
		for i, n := range v {
			out[i] = nodeMod{mod: m, node: n}
		}
		v = out
	}
	return v
}

// Attr adds the given HTML attributes
// to the outermost HTML element generated by v.
func (v base) Attr(a ...domi.Attr) View { return v.Modify(modAttr{attr: domi.Group(a...)}) }

// Background fills the background of v with c.
func (v base) Background(c Color) View { return v.Modify(Background(c)) }

// BorderShape sets the shape of v's border.
func (v base) BorderShape(s Shape) View { return v.Modify(BorderShape(s)) }

// Class adds the given CSS classes
// to the outermost HTML element generated by v.
func (v base) Class(c ...string) View { return v.Modify(modAttr{attr: attr.Class(c...)}) }

// FixedSize fixes v at its ideal size.
// This can cause it to exceed the bounds of its container.
func (v base) FixedSize() View { return v.Modify(modFixedSize{}) }

// Font sets the font size for text in v.
func (v base) Font(f FontSize) View { return v.Modify(Font(f)) }

// Foreground uses c to draw foreground elements in v,
// such as text.
func (v base) Foreground(c Color) View { return v.Modify(Foreground(c)) }

// Opacity sets v's opacity to x, from 0 (transparent) to 1 (opaque).
func (v base) Opacity(x float64) View { return v.Modify(Opacity(x)) }

// Tag sets the HTML tag name
// of the outermost HTML element generated by v.
// If v already has a tag name, Tag panics.
func (v base) Tag(name string) View { return v.Modify(modTag{name: name}) }

// NOTE: no exported construcor.
type modAttr struct{ attr domi.Attr }

func (m modAttr) applyTo(x box) box {
	x.add(m.attr)
	return x
}

type modBackground struct{ c Color }

// Background fills the background of a view with c.
func Background(c Color) Modifier { return modBackground{c} }

func (m modBackground) applyTo(x box) box {
	if m.c != "" {
		x.setStyle("background-color", string(m.c))
	}
	return x
}

type modBorderShape struct{ s Shape }

// BorderShape sets the shape of a view's border.
func BorderShape(s Shape) Modifier { return modBorderShape{s} }

func (m modBorderShape) applyTo(x box) box {
	type key struct{}
	x.modClass.Set(key{}, m.s.class())
	return x
}

// NOTE: no exported construcor.
type modFixedSize struct{}

func (modFixedSize) applyTo(x box) box {
	x.add(attr.Class("ui-fixed-size"))
	x.fills = 0
	x.rigid = Horizontal | Vertical
	return x
}

func (modFixedSize) context(rc renderContext) renderContext {
	rc.unbounded = Horizontal | Vertical
	return rc
}

type modFont struct{ f FontSize }

// Font sets the font size for text in a view.
func Font(f FontSize) Modifier { return modFont{f: f} }

func (m modFont) applyTo(x box) box {
	type key struct{}
	x.modClass.Set(key{}, m.f.class())
	return x
}

type modForeground struct{ c Color }

// Foreground uses c to draw foreground elements in a view,
// such as text.
func Foreground(c Color) Modifier { return modForeground{c: c} }

func (m modForeground) applyTo(x box) box {
	if m.c != "" {
		x.setStyle("color", string(m.c))
	}
	return x
}

type modOpacity struct{ x float64 }

// Opacity sets a view's opacity to x, from 0 (transparent) to 1 (opaque).
func Opacity(x float64) Modifier { return modOpacity{x: x} }

func (m modOpacity) applyTo(x box) box {
	x.setStyle("opacity", fmt.Sprintf("%g", m.x))
	return x
}

// NOTE: no exported construcor.
type modTag struct{ name string }

func (m modTag) applyTo(x box) box {
	if x.tag != "" {
		panic(fmt.Sprintf("ui: Tag(%q) on a view already tagged %q", m.name, x.tag))
	}
	x.tag = m.name
	return x
}

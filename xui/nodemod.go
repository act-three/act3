package ui

import (
	"ily.dev/domi"
	"ily.dev/domi/attr"
)

// A Modifier configures the behavior of a View.
// It can be applied with [View.Modify].
//
// It is usually more convenient to call modifier methods directly on View.
//
// A style modifier behaves as if it were applied to a
// layout-transparent element wrapping the modified view.
// The renderer may collapse modifiers onto a single element
// only where that preserves the wrapper semantics.
type Modifier interface {
	modify(node) node
}

// A nodeEnv adjusts the environment for its subtree.
type nodeEnv struct {
	f    func(environment) environment
	node node
}

func (m nodeEnv) render(env environment) plan {
	return m.node.render(m.f(env))
}

// Modify applies the given modifiers to v in order from left to right.
func (v base) Modify(mods ...Modifier) View {
	for _, m := range mods {
		out := make(base, len(v))
		for i, n := range v {
			out[i] = m.modify(n)
		}
		v = out
	}
	return v
}

// Attr adds the given HTML attributes
// to the outermost HTML element generated by v.
func (v base) Attr(a ...domi.Attr) View { return v.Modify(modAttr{attr: domi.Group(a...)}) }

// Background fills the background of v with c.
func (v base) Background(c Color) View { return v.Modify(Background(c)) }

// BorderShape sets the shape of v's border.
func (v base) BorderShape(s Shape) View { return v.Modify(BorderShape(s)) }

// Class adds the given CSS classes
// to the outermost HTML element generated by v.
func (v base) Class(c ...string) View { return v.Modify(modAttr{attr: attr.Class(c...)}) }

// FixedSize fixes v at its ideal size.
// This can cause it to exceed the bounds of its container.
func (v base) FixedSize() View { return v.Modify(modFixedSize{}) }

// Font sets the font size for text in v.
func (v base) Font(f FontSize) View { return v.Modify(Font(f)) }

// Foreground uses c to draw foreground elements in v,
// such as text.
func (v base) Foreground(c Color) View { return v.Modify(Foreground(c)) }

// Opacity sets v's opacity to x, from 0 (transparent) to 1 (opaque).
func (v base) Opacity(x float64) View { return v.Modify(Opacity(x)) }

// Tag sets the HTML tag name
// of the outermost HTML element generated by v.
func (v base) Tag(name string) View { return v.Modify(modTag{name: name}) }

// NOTE: no exported construcor.
type modAttr struct{ attr domi.Attr }

func (m modAttr) modify(n node) node { return nodeEnv{f: m.environment, node: n} }

// environment prepends the attributes to those already set,
// keeping an inner modifier's attributes before an outer's,
// so they land on the consuming box in application order.
func (m modAttr) environment(env environment) environment {
	a, _ := env.attrs.Take()
	env.attrs.Set(domi.Group(m.attr, a))
	return env
}

type wrapBackground struct {
	c    Color
	node node
}

// Background fills the background of a view with c.
func Background(c Color) Modifier { return wrapBackground{c: c} }

func (w wrapBackground) modify(n node) node { w.node = n; return w }

func (w wrapBackground) render(env environment) plan {
	p, m := wrapSubview(env, w.node)
	p.add(attr.Class("ui-mod"))
	if w.c != "" {
		p.pres.background = &w.c
	}
	m.applyTo(&p)
	return p
}

type modBorderShape struct{ s Shape }

// BorderShape sets the shape of a view's border.
//
// The shape is drawn by the modified view itself:
// it inherits down to the first box under the modifier,
// which consumes it and paints itself in the given shape.
// A repeated BorderShape is therefore inert:
// the innermost shape is written last and wins.
// BorderShape does not clip;
// content that overflows the shape is drawn in full.
func BorderShape(s Shape) Modifier { return modBorderShape{s} }

func (m modBorderShape) modify(n node) node { return nodeEnv{f: m.environment, node: n} }

func (m modBorderShape) environment(env environment) environment {
	env.shape.Set(m.s)
	return env
}

// NOTE: no exported construcor.
type modFixedSize struct{}

func (m modFixedSize) modify(n node) node { return nodeEnv{f: m.environment, node: n} }

// environment gives the subtree unbounded available space on both axes,
// so the first box takes its ideal size (see [mise]).
// The marker class rides the mise's attrs.
func (modFixedSize) environment(env environment) environment {
	env.unbounded = Horizontal | Vertical
	a, _ := env.attrs.Take()
	env.attrs.Set(domi.Group(attr.Class("ui-fixed-size"), a))
	return env
}

type modFont struct{ f FontSize }

// Font sets the font size for text in a view.
func Font(f FontSize) Modifier { return modFont{f} }

func (m modFont) modify(n node) node { return nodeEnv{f: m.environment, node: n} }

func (m modFont) environment(env environment) environment {
	if m.f.class() != "" {
		env.font.Set(m.f)
	}
	return env
}

type modForeground struct{ c Color }

// Foreground uses c to draw foreground elements in a view,
// such as text.
func Foreground(c Color) Modifier { return modForeground{c} }

func (m modForeground) modify(n node) node { return nodeEnv{f: m.environment, node: n} }

func (m modForeground) environment(env environment) environment {
	if m.c != "" {
		env.fg.Set(m.c)
	}
	return env
}

type wrapOpacity struct {
	x    float64
	node node
}

// Opacity sets a view's opacity to x, from 0 (transparent) to 1 (opaque).
// Nested opacities multiply:
// v.Opacity(0.5).Opacity(0.5) draws v at a quarter of full opacity.
func Opacity(x float64) Modifier { return wrapOpacity{x: x} }

func (w wrapOpacity) modify(n node) node { w.node = n; return w }

func (w wrapOpacity) render(env environment) plan {
	p, m := wrapSubview(env, w.node)
	p.add(attr.Class("ui-mod"))
	p.pres.opacity = &w.x
	m.applyTo(&p)
	return p
}

// NOTE: no exported construcor.
type modTag struct{ name string }

func (m modTag) modify(n node) node { return nodeEnv{f: m.environment, node: n} }

func (m modTag) environment(env environment) environment {
	env.tag.Set(m.name)
	return env
}

// A View is a user interface element,
// with modifiers to change its appearance and behavior.
//
// Views are immutable.
// A modifier always returns a new view
// that is a modified version of the underlying view.
//
// You can create custom views by writing functions that return View values.
//
//	func MyView() View {
//	    return Text("hello, world!")
//	}
//
// Compose the View by combining one or more of the built-in views
// provided in this package,
// like the Text view above,
// plus other custom view functions you define.
type View interface {
	// Background fills the background of the receiver.
	Background(Color) View

	// BorderShape sets the shape of the receiver's border.
	BorderShape(Shape) View

	// FixedSize fixes the receiver at its ideal size.
	FixedSize() View

	// Font sets the font size for text in the receiver.
	Font(FontSize) View

	// Foreground uses c to draw foreground elements in the receiver,
	// such as text.
	Foreground(c Color) View

	// Frame positions the receiver inside an invisible frame with the
	// given dimensions and alignment.
	//
	// Note that type Alignment satisfies FrameOption.
	Frame(...FrameOption) View

	// FrameBounds positions the receiver inside an invisible frame with
	// the given bounds and alignment.
	//
	// Note that type Alignment satisfies FrameBoundsOption.
	FrameBounds(...FrameBoundsOption) View

	// LayerOver displays o over the receiver. Opaque regions of o
	// obscure the receiver where they overlap.
	//
	// The given Alignment sets the position of o relative to the receiver.
	LayerOver(a Alignment, o View) View

	// LayerUnder displays u under the receiver. Opaque regions of the
	// receiver obscure u where they overlap.
	//
	// The given Alignment sets the position of u relative to the receiver.
	LayerUnder(a Alignment, u View) View

	// Opacity sets the receiver's opacity to x, from 0 (transparent) to
	// 1 (opaque).
	Opacity(x float64) View

	// Padding adds the empty space defined by s around the receiver. If
	// more than one value s is provided, they are added together.
	Padding(s ...EdgeSpace) View

	// Modify applies the given modifiers to the receiver in order from
	// left to right.
	Modify(...Modifier) View

	// Attr adds the given HTML attributes to the outermost HTML element
	// generated by the receiver.
	Attr(...domi.Attr) View

	// Class adds the given CSS classes to the outermost HTML element
	// generated by the receiver.
	Class(...string) View

	// Tag sets the HTML tag name of the outermost HTML element
	// generated by the receiver.
	Tag(string) View

	nodes() []node
}

// base is the shared concrete View implementation.
// A view is a list of nodes rendered in sequence.
// Most views hold a single node, but  [Group] and [For] hold one per member.
// An applied modifier modifies each node individually.
type base []node

func (v base) nodes() []node { return v }

// A node is a unary view.
// Its whole job is to lower itself to a single box.
type node interface {
	render(environment) box
}

type containerKind int

const (
	containerGrid containerKind = iota
	containerFlex
)

// environment carries the top-down state of a lowering pass.
type environment struct {
	lc        layoutContext
	container containerKind
	unbounded AxisSet
	sheet     *sheet.Sheet

	// Consumed by render when constructing a box.
	shape slot.Slot[Shape]
	attrs slot.Slot[domi.Attr]
	tag   slot.Slot[string]
}

// shapeClass consumes the pending border shape as its class attribute.
// It returns nil when no shape is pending.
func (env *environment) shapeClass() domi.Attr {
	if s, ok := env.shape.Take(); ok {
		return attr.Class(s.class())
	}
	return nil
}

// pending is a set of consumed modifier effects, ready to land on a box.
type pending struct {
	attrs     domi.Attr // added to the box, including the shape's class
	tag       string    // the box's tag, unless the box has its own
	unbounded AxisSet   // axes on which the box takes its ideal size
}

// takePending consumes the environment's pending modifier effects.
// A node that produces a box takes them before rendering subviews,
// so each effect stops at the first box under its modifier.
func (env *environment) takePending() pending {
	p := pending{attrs: env.shapeClass(), unbounded: env.unbounded}
	if a, ok := env.attrs.Take(); ok {
		p.attrs = domi.Group(p.attrs, a)
	}
	p.tag, _ = env.tag.Take()
	return p
}

// applyTo lands the pending effects on the box.
// The innermost tag wins, so the box's own tag is kept if it has one.
// An unbounded axis takes the box's ideal size, which is definite,
// so the axis is rigid and a fill request on it is meaningless.
func (p pending) applyTo(x *box) {
	x.add(p.attrs)
	x.tag = cmp.Or(x.tag, p.tag)
	x.fills &^= p.unbounded
	x.rigid |= p.unbounded
}

// A box is an HTML element under construction.
type box struct {
	tag     string
	key     string
	fills   AxisSet // A fill request is the physical axes a box wants to fill.
	rigid   AxisSet
	attrs   domi.Attr
	styles  sheet.StyleSet
	content domi.Node
	raw     domi.Node
}

func (x *box) add(a domi.Attr) { x.attrs = domi.Group(x.attrs, a) }

// setStyle adds a dynamic CSS declaration to the box.
// Setting the same property again replaces its value.
func (x *box) setStyle(property, value string) { x.styles.Set(property, value) }

// styleClass returns the generated class for the box's dynamic styles.
func (x box) styleClass(env environment) domi.Attr {
	if x.styles.IsEmpty() {
		return nil
	}
	return attr.Class(env.sheet.ClassFor(x.styles))
}

// subviewsRendered is a generic combinator for lists of subviews.
// It renders the given views and merges their fill requests.
func subviewsRendered(env environment, vs ...View) (domi.Node, AxisSet) {
	var ns []domi.Node
	var f AxisSet
	for _, v := range vs {
		for _, n := range v.nodes() {
			x := n.render(env)
			f |= x.fills
			ns = append(ns, x.build(env))
		}
	}
	return domi.Fragment(ns...), f
}

// build builds x as an HTML node.
func (x box) build(env environment) domi.Node {
	n := x.raw
	if n == nil {
		// Keep the generated class after the named classes in rendered output.
		a := domi.Group(x.fills.fillAttr(env), x.rigid.rigidAttr(env), x.styleClass(env))
		n = domi.Tag(cmp.Or(x.tag, "div"), x.attrs, a)(x.content)
	}
	if x.key != "" {
		n = domi.WithKey(x.key, n)
	}
	return n
}
